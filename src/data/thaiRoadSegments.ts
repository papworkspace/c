/**
 * ค้นหาช่วงถนนสายหลักในรัศมีใกล้เคียงกับพิกัด (lat, lng) ของสถานที่ที่ผู้ใช้ค้นหา
 * เพื่อให้แม้ผู้ใช้ค้นหาด้วย "ชื่อสถานที่" (เช่น อนุสรณ์สถาน, โรงพยาบาล, ตลาด, ห้าง, วัด)
 * ระบบจะดึงถนนสายหลักรอบๆ พิกัดนั้นขึ้นมาแสดงให้ทันทีพร้อมระยะทางจริง
 */
export function findNearbyRoadSegmentsByCoords(
  lat: number,
  lng: number,
  maxRadiusKm = 6.5,
  limit = 6
): Array<{ segment: RoadSegmentEntry; distanceKm: number }> {
  const matches: Array<{ segment: RoadSegmentEntry; distanceKm: number }> = [];
  for (const seg of CURATED_ROAD_SEGMENTS) {
    // Bounding box filter ก่อนคำนวณ Haversine เพื่อความเร็วสูงสุด
    if (Math.abs(seg.lat - lat) > 0.08 || Math.abs(seg.lng - lng) > 0.08) {
      continue;
    }
    const dist = Number(calculateDistanceKm(lat, lng, seg.lat, seg.lng).toFixed(1));
    if (dist <= maxRadiusKm) {
      matches.push({ segment: seg, distanceKm: dist });
    }
  }
  return matches.sort((a, b) => a.distanceKm - b.distanceKm).slice(0, limit);
}
